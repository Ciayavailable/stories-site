export type MenuItem = {
  name: string;
  description?: string;
  /** Цена в рублях; строка — чтобы поддерживать несколько объёмов: «230 / 310 / 370» */
  price?: string;
  hit?: boolean;
};

export type MenuGroup = {
  /** Подзаголовок внутри категории (например «Классика»); без заголовка — просто список */
  title?: string;
  items: MenuItem[];
};

/** Страница внутри категории — для длинных разделов (например «Кофе») */
export type MenuPage = {
  /** Подпись страницы на переключателе */
  label: string;
  groups: MenuGroup[];
};

export type MenuCategory = {
  id: string;
  label: string;
  note?: string;
  groups: MenuGroup[];
  /** Если заданы — содержимое категории показывается постранично вместо groups */
  pages?: MenuPage[];
};

